const frameCache = new Map();
async function loadImage(path) {
  if (frameCache.has(path)) return frameCache.get(path);
  const img = new Image();
  const src = window.__assetMap?.[path] || path;
  const p = new Promise((resolve, reject) => {
    img.onload = () => resolve(img);
    img.onerror = () => reject(new Error('Không tải được ảnh ' + path));
  });
  img.src = src;
  frameCache.set(path, p);
  return p;
}

function mascotImage(id) {
  return loadImage(`assets/personas/${id}.svg`);
}

function roundRect(ctx, x, y, w, h, r, fill, stroke, strokeWidth = 1) {
  ctx.beginPath();
  ctx.roundRect(x, y, w, h, r);
  if (fill) {
    ctx.fillStyle = fill;
    ctx.fill();
  }
  if (stroke) {
    ctx.strokeStyle = stroke;
    ctx.lineWidth = strokeWidth;
    ctx.stroke();
  }
}

function drawGingham(ctx, w, h, lightColor, darkColor, step = 56) {
  ctx.fillStyle = lightColor;
  ctx.fillRect(0, 0, w, h);

  ctx.fillStyle = darkColor;
  ctx.globalAlpha = 0.42;

  // Vertical bands
  for (let x = 0; x < w; x += step * 2) {
    ctx.fillRect(x, 0, step, h);
  }
  // Horizontal bands
  for (let y = 0; y < h; y += step * 2) {
    ctx.fillRect(0, y, w, step);
  }

  ctx.globalAlpha = 1.0;
}

function drawSparkle(ctx, x, y, size, color = '#ffffff') {
  ctx.save();
  ctx.translate(x, y);
  ctx.fillStyle = color;
  ctx.beginPath();
  for (let i = 0; i < 4; i++) {
    const angle = (i * Math.PI) / 2;
    ctx.lineTo(Math.cos(angle) * size, Math.sin(angle) * size);
    ctx.lineTo(Math.cos(angle + Math.PI / 4) * (size * 0.22), Math.sin(angle + Math.PI / 4) * (size * 0.22));
  }
  ctx.closePath();
  ctx.fill();
  ctx.restore();
}

function drawFlower(ctx, x, y, r, petalColor, strokeColor = '#2b1c24') {
  ctx.save();
  ctx.translate(x, y);
  for (let i = 0; i < 5; i++) {
    const angle = (i * 2 * Math.PI) / 5 - Math.PI / 2;
    const px = Math.cos(angle) * r;
    const py = Math.sin(angle) * r;
    ctx.beginPath();
    ctx.arc(px, py, r * 0.85, 0, Math.PI * 2);
    ctx.fillStyle = petalColor;
    ctx.fill();
    ctx.strokeStyle = strokeColor;
    ctx.lineWidth = 3.5;
    ctx.stroke();
  }
  // Center pistil
  ctx.beginPath();
  ctx.arc(0, 0, r * 0.55, 0, Math.PI * 2);
  ctx.fillStyle = '#ffffff';
  ctx.fill();
  ctx.strokeStyle = strokeColor;
  ctx.lineWidth = 3;
  ctx.stroke();
  ctx.restore();
}

function drawBarcode(ctx, x, y, w, h, color = '#2b1c24') {
  ctx.save();
  ctx.strokeStyle = color;
  ctx.fillStyle = color;
  ctx.lineCap = 'round';

  const pattern = [2, 1, 4, 1, 1, 3, 2, 1, 5, 2, 1, 3, 1, 4, 2, 1, 1, 3, 2, 4, 1, 2, 5, 1, 3, 2, 1, 4];
  let curX = x;
  const barW = w / 48;

  for (let i = 0; i < pattern.length && curX < x + w; i++) {
    const sw = Math.min(pattern[i] * 1.5, 6.5);
    const varH = (i % 5 === 0) ? h * 0.78 : (i % 3 === 0) ? h * 0.9 : h;
    const offsetY = h - varH;

    ctx.lineWidth = sw;
    ctx.beginPath();
    ctx.moveTo(curX, y + offsetY);
    ctx.lineTo(curX, y + h);
    ctx.stroke();

    curX += sw + barW;
  }
  ctx.restore();
}

function drawWavyLine(ctx, x, y, w, color = '#2b1c24', amp = 2.5, freq = 12) {
  ctx.save();
  ctx.strokeStyle = color;
  ctx.lineWidth = 2.2;
  ctx.lineCap = 'round';
  ctx.beginPath();
  ctx.moveTo(x, y);
  for (let cx = x; cx <= x + w; cx += 2) {
    const cy = y + Math.sin(((cx - x) / freq) * Math.PI) * amp;
    ctx.lineTo(cx, cy);
  }
  ctx.stroke();
  ctx.restore();
}

export async function drawPersonaCard(canvas, p, nickname = 'YOUR NAME', date = new Date()) {
  if (document.fonts?.ready) {
    try { await document.fonts.ready; } catch {}
  }

  const ctx = canvas.getContext('2d');
  const W = 900;
  const H = 1190;
  canvas.width = W;
  canvas.height = H;

  const v = personaStyles[p.id] || personaStyles.bee;

  ctx.clearRect(0, 0, W, H);

  // 1. STORY BACKDROP (Gingham Caro Pattern)
  drawGingham(ctx, W, H, v.ginghamLight, v.ginghamDark, 54);

  // Sparkles & Star Doodles on backdrop
  const sparkles = [
    [110, 110, 24], [780, 140, 22], [90, 480, 18], [810, 520, 26],
    [130, 890, 22], [790, 930, 28], [450, 75, 20], [450, 1115, 22],
    [240, 1135, 14], [670, 1130, 16]
  ];
  for (const [sx, sy, sr] of sparkles) {
    drawSparkle(ctx, sx, sy, sr, '#ffffff');
    drawSparkle(ctx, sx, sy, sr * 0.45, v.headerBg);
  }

  // Crosses (+) & Dots around the backdrop
  ctx.fillStyle = '#ffffff';
  ctx.font = '900 24px sans-serif';
  ctx.fillText('+', 190, 80);
  ctx.fillText('+', 710, 95);
  ctx.fillText('+', 820, 740);
  ctx.fillText('+', 70, 720);

  // Hand-drawn white curved doodle arcs at corners
  ctx.save();
  ctx.strokeStyle = 'rgba(255, 255, 255, 0.9)';
  ctx.lineWidth = 7;
  ctx.lineCap = 'round';
  // Top-left doodle arc
  ctx.beginPath();
  ctx.arc(85, 250, 45, Math.PI * 0.7, Math.PI * 1.35);
  ctx.stroke();
  // Bottom-left doodle arc
  ctx.beginPath();
  ctx.arc(80, 960, 55, Math.PI * 0.6, Math.PI * 1.2);
  ctx.stroke();
  // Top-right doodle arc
  ctx.beginPath();
  ctx.arc(815, 260, 50, -Math.PI * 0.3, Math.PI * 0.35);
  ctx.stroke();
  // Bottom-right doodle arc
  ctx.beginPath();
  ctx.arc(815, 980, 50, -Math.PI * 0.25, Math.PI * 0.4);
  ctx.stroke();
  ctx.restore();

  // 2. TILTED CENTRAL ID CARD (rotate ~ -2.4deg)
  const cardW = 790;
  const cardH = 500;
  const cardCenterX = W / 2;
  const cardCenterY = H / 2 - 15;

  ctx.save();
  ctx.translate(cardCenterX, cardCenterY);
  ctx.rotate((-2.4 * Math.PI) / 180);

  const cardLeft = -cardW / 2;
  const cardTop = -cardH / 2;

  // Drop Shadow
  ctx.save();
  ctx.shadowColor = 'rgba(45, 28, 36, 0.22)';
  ctx.shadowBlur = 24;
  ctx.shadowOffsetX = 6;
  ctx.shadowOffsetY = 16;
  roundRect(ctx, cardLeft, cardTop, cardW, cardH, 32, '#fffdf8', null);
  ctx.restore();

  // Card Body (Warm cream white)
  roundRect(ctx, cardLeft, cardTop, cardW, cardH, 32, '#fffdf8', v.ink, 6.5);

  // Card Header Banner (Cute rounded banner across top)
  const bannerMargin = 16;
  const bannerW = cardW - bannerMargin * 2;
  const bannerH = 78;
  const bannerX = cardLeft + bannerMargin;
  const bannerY = cardTop + bannerMargin;

  roundRect(ctx, bannerX, bannerY, bannerW, bannerH, 18, v.headerBg, v.ink, 5.5);

  // Header Title
  ctx.fillStyle = v.headerText;
  ctx.font = '800 38px "Baloo 2", "Arial Rounded MT Bold", cursive, sans-serif';
  ctx.textAlign = 'center';
  ctx.textBaseline = 'middle';
  ctx.letterSpacing = '1px';
  ctx.fillText('★  TEAM-CRAFT LICENSE  ★', 0, bannerY + bannerH / 2 + 1);

  // 3. LEFT COLUMN: Photo Frame & Mascot
  const photoW = 245;
  const photoH = 265;
  const photoX = cardLeft + 32;
  const photoY = bannerY + bannerH + 20;

  // Photo box frame
  roundRect(ctx, photoX, photoY, photoW, photoH, 16, v.photoBg, v.ink, 5);

  // Mascot Image
  try {
    const mascot = await mascotImage(p.id);
    const pad = 12;
    ctx.drawImage(mascot, photoX + pad, photoY + pad, photoW - pad * 2, photoH - pad * 2);
  } catch (err) {
    console.error('Cannot load mascot:', err);
  }

  // Handwritten Mascot Signature / Name underneath photo
  ctx.font = '800 23px "Baloo 2", "Comic Sans MS", cursive, sans-serif';
  const nameW = ctx.measureText(v.name).width;
  const photoCenterX = photoX + photoW / 2;

  // Tiny cute flower placed with ample breathing room to the left of the signature (no overlap)
  const flowerX = Math.min(photoX + 13, photoCenterX - nameW / 2 - 16);
  drawFlower(ctx, flowerX, photoY + photoH + 24, 6.5, v.flower, v.ink);

  ctx.fillStyle = v.accent;
  ctx.textAlign = 'center';
  ctx.textBaseline = 'top';
  ctx.fillText(v.name, photoCenterX, photoY + photoH + 12);

  // 4. RIGHT COLUMN: Information & 4 Behavioral Indicators
  const infoX = cardLeft + 305;
  const infoY = bannerY + bannerH + 18;

  // Player ID / Nickname row (up to 22 chars with auto-scale & dynamic wavy signature)
  ctx.textAlign = 'left';
  ctx.textBaseline = 'top';
  ctx.fillStyle = v.ink;
  const rawId = (nickname && nickname.trim()) ? nickname.trim() : 'YOUR NAME';
  const displayId = rawId.toUpperCase().slice(0, 22);

  const maxNickW = 380;
  let nickFontSize = 28;
  ctx.font = `800 ${nickFontSize}px "Baloo 2", "Lexend", monospace`;
  while (ctx.measureText(displayId).width > maxNickW && nickFontSize > 18) {
    nickFontSize -= 1;
    ctx.font = `800 ${nickFontSize}px "Baloo 2", "Lexend", monospace`;
  }
  ctx.fillText(displayId, infoX, infoY + 2, maxNickW);

  // Two hand-drawn wavy signature scribble lines dynamically scaling with the ID length
  const nickW = Math.max(ctx.measureText(displayId).width, 180);
  drawWavyLine(ctx, infoX, infoY + 38, Math.min(nickW + 24, 370), v.ink, 2.2, 11);
  drawWavyLine(ctx, infoX, infoY + 45, Math.min(nickW * 0.78, 280), v.ink, 1.8, 9);

  // Title: Persona Title (Large Bold Title with dynamic auto-scaling to avoid overflow)
  const maxTitleW = cardW - 305 - 48; // ~437px safe width inside card
  let titleFontSize = 31;
  ctx.font = `800 ${titleFontSize}px "Baloo 2", "Lexend", cursive, sans-serif`;
  while (ctx.measureText(p.title).width > maxTitleW && titleFontSize > 20) {
    titleFontSize -= 1;
    ctx.font = `800 ${titleFontSize}px "Baloo 2", "Lexend", cursive, sans-serif`;
  }
  ctx.fillStyle = v.ink;
  ctx.fillText(p.title, infoX, infoY + 64, maxTitleW);

  // Subtitle / Caption (Personality / Clan)
  ctx.fillStyle = '#6e5461';
  ctx.font = '600 20px "Lexend", sans-serif';
  ctx.fillText(v.caption, infoX, infoY + 107, maxTitleW);

  // 4 Behavioral Indicators (4 columns)
  const statsY = infoY + 155;
  const colSpacing = 112;

  v.stats.forEach((st, idx) => {
    const colX = infoX + idx * colSpacing;
    // Label
    ctx.fillStyle = '#8c707d';
    ctx.font = '600 13px "Lexend", sans-serif';
    ctx.textAlign = 'center';
    ctx.fillText(st.label, colX + 42, statsY);

    // Value
    ctx.fillStyle = v.ink;
    ctx.font = '800 21px "Baloo 2", "Lexend", sans-serif';
    ctx.fillText(st.val, colX + 42, statsY + 22);
  });

  // Barcode in Bottom-Right
  const barcodeX = infoX;
  const barcodeY = statsY + 66;
  drawBarcode(ctx, barcodeX, barcodeY, 265, 36, v.ink);

  // Barcode caption
  ctx.fillStyle = '#9b808e';
  ctx.font = '500 12px "Lexend", monospace';
  ctx.textAlign = 'left';
  ctx.fillText(v.code + ' • OFFICIAL ID', barcodeX, barcodeY + 42);

  // 1-2 Cute Pink Cherry Blossom Flowers in Bottom-Right corner of Card
  drawFlower(ctx, cardLeft + cardW - 75, cardTop + cardH - 85, 20, v.flower, v.ink);
  drawFlower(ctx, cardLeft + cardW - 38, cardTop + cardH - 45, 12, v.flower, v.ink);

  ctx.restore(); // Restore rotated card coordinate space

  // 5. BOTTOM STORY FOOTER (Outside Card, on Story Backdrop)
  ctx.fillStyle = v.ink;
  ctx.font = '800 24px "Baloo 2", cursive, sans-serif';
  ctx.textAlign = 'center';
  ctx.textBaseline = 'middle';
  ctx.fillText('✦ THẺ HÀNH NGHỀ TEAMWORK ✦', W / 2, H - 75);

  ctx.fillStyle = '#7a5a6a';
  ctx.font = '500 17px "Lexend", sans-serif';
  ctx.fillText(v.trait + ' · TEAM-CRAFT SIMULATOR', W / 2, H - 42);

  return canvas;
}

